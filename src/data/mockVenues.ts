export function getVenueDisplayImage(venue: GroundVenue, selectedSport?: string): string {
  if (selectedSport && selectedSport !== "ALL") {
    const matchingPitch = venue.pitches.find((p) => p.sportType === selectedSport);
    if (matchingPitch) {
      return SPORT_IMAGES[matchingPitch.sportType];
    }
  }
  return venue.featuredImg;
}

